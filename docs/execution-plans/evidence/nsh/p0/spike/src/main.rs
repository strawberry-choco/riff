// The `windows_subsystem = "windows"` attribute the nsh rust template sets is
// deliberately omitted here so `cargo run` keeps stdout for the spike's logs.

#[cfg(target_os = "linux")]
use nsh_platform_linux as platform;
#[cfg(target_os = "macos")]
use nsh_platform_macos as platform;
#[cfg(target_os = "windows")]
use nsh_platform_windows as platform;

#[cfg(any(target_os = "linux", target_os = "macos", target_os = "windows"))]
fn main() -> impl std::process::Termination {
    env_logger::init();
    platform::run_app(
        platform::AppSource::Rust(platform::Root::of::<riff_gui_nsh_spike::App>()),
        platform::AppOptions {
            title: "riff".to_owned(),
            #[cfg(any(target_os = "linux", target_os = "windows"))]
            app_id: "io.github.strawberry-choco.riff".to_owned(),
            size: (480, 640),
            ..Default::default()
        },
    )
}